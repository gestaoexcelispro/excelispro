function TableRow({
  children,
  alternate,
}) {
  return (
    <View
      wrap={false}
      style={[
        pdfStyles.tableRow,
        alternate
          ? pdfStyles.tableRowAlternate
          : null,
      ]}
    >
      {children}
    </View>
  );
}

function TableCell({
  children,
  width,
  strong,
  tone,
}) {
  let style = [
    pdfStyles.tableCell,
    {
      width,
    },
  ];

  if (strong) {
    style.push(
      pdfStyles.tableCellStrong
    );
  }

  if (
    tone ===
    'success'
  ) {
    style.push(
      pdfStyles.tableCellSuccess
    );
  }

  if (
    tone ===
    'warning'
  ) {
    style.push(
      pdfStyles.tableCellWarning
    );
  }

  if (
    tone ===
    'danger'
  ) {
    style.push(
      pdfStyles.tableCellDanger
    );
  }

  return (
    <Text
      style={
        style
      }
    >
      {safeText(
        children
      )}
    </Text>
  );
}


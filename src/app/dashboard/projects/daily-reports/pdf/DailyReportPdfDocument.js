function ProductionSection({
  production,
}) {
  return (
    <View
      style={
        pdfStyles.section
      }
    >
      <SectionHeader
        number="04"
        title="Production"
        description="Production recorded by project location and service."
      />

      {production.length ===
      0 ? (
        <EmptyState
          title="No production records"
          text="No production quantities were recorded for this Daily Report."
        />
      ) : (
        <View
          style={
            pdfStyles.table
          }
        >
          <View
            style={
              pdfStyles.tableHeader
            }
          >
            <HeaderCell width="20%">
              Location
            </HeaderCell>

            <HeaderCell width="18%">
              Service
            </HeaderCell>

            <HeaderCell width="10%">
              Plan
            </HeaderCell>

            <HeaderCell width="10%">
              Actual
            </HeaderCell>

            <HeaderCell width="12%">
              Cum.
            </HeaderCell>

            <HeaderCell width="12%">
              Progress
            </HeaderCell>

            <HeaderCell width="18%">
              Status
            </HeaderCell>
          </View>

          {production.map(
            (
              item,
              index
            ) => {
              const progress =
                getProductionProgress(
                  item.cumulative_quantity,
                  item.scope_quantity
                );

              const variance =
                getVariance(
                  item.planned_quantity,
                  item.actual_quantity
                );

              let tone;

              if (
                variance !==
                  null &&
                variance <
                  0
              ) {
                tone =
                  'warning';
              }

              if (
                item.production_status ===
                'completed'
              ) {
                tone =
                  'success';
              }

              return (
                <TableRow
                  key={
                    item.id ||
                    index
                  }
                  alternate={
                    index % 2 ===
                    1
                  }
                >
                  <TableCell
                    width="20%"
                    strong
                  >
                    {item.location_name}
                  </TableCell>

                  <TableCell width="18%">
                    {item.service_name}
                  </TableCell>

                  <TableCell width="10%">
                    {formatQuantity(
                      item.planned_quantity,
                      item.unit
                    )}
                  </TableCell>

                  <TableCell width="10%">
                    {formatQuantity(
                      item.actual_quantity,
                      item.unit
                    )}
                  </TableCell>

                  <TableCell width="12%">
                    {formatQuantity(
                      item.cumulative_quantity,
                      item.unit
                    )}
                  </TableCell>

                  <TableCell width="12%">
                    {progress ===
                    null
                      ? '—'
                      : formatPercentage(
                          progress
                        )}
                  </TableCell>

                  <TableCell
                    width="18%"
                    tone={
                      tone
                    }
                  >
                    {formatProductionStatus(
                      item.production_status
                    )}
                  </TableCell>
                </TableRow>
              );
            }
          )}
        </View>
      )}
    </View>
  );
}


function SummaryCard({
  label,
  value,
  helper,
  tone,
}) {
  let innerStyle =
    pdfStyles.summaryCardInner;

  let valueStyle =
    pdfStyles.summaryValue;

  if (
    tone ===
    'success'
  ) {
    innerStyle = [
      pdfStyles.summaryCardInner,
      pdfStyles.summaryCardSuccess,
    ];

    valueStyle = [
      pdfStyles.summaryValue,
      pdfStyles.summaryValueSuccess,
    ];
  }

  if (
    tone ===
    'warning'
  ) {
    innerStyle = [
      pdfStyles.summaryCardInner,
      pdfStyles.summaryCardWarning,
    ];

    valueStyle = [
      pdfStyles.summaryValue,
      pdfStyles.summaryValueWarning,
    ];
  }

  if (
    tone ===
    'danger'
  ) {
    innerStyle = [
      pdfStyles.summaryCardInner,
      pdfStyles.summaryCardDanger,
    ];

    valueStyle = [
      pdfStyles.summaryValue,
      pdfStyles.summaryValueDanger,
    ];
  }

  return (
    <View
      style={
        pdfStyles.summaryCard
      }
    >
      <View
        style={
          innerStyle
        }
      >
        <Text
          style={
            pdfStyles.summaryLabel
          }
        >
          {label}
        </Text>

        <Text
          style={
            valueStyle
          }
        >
          {safeText(
            value
          )}
        </Text>

        {helper && (
          <Text
            style={
              pdfStyles.summaryHelper
            }
          >
            {helper}
          </Text>
        )}
      </View>
    </View>
  );
}

function InfoBox({
  label,
  value,
  width = 'half',
}) {
  let wrapperStyle =
    pdfStyles.infoCellHalf;

  if (
    width ===
    'third'
  ) {
    wrapperStyle =
      pdfStyles.infoCellThird;
  }

  if (
    width ===
    'quarter'
  ) {
    wrapperStyle =
      pdfStyles.infoCellQuarter;
  }

  return (
    <View
      style={
        wrapperStyle
      }
    >
      <View
        style={
          pdfStyles.infoBox
        }
      >
        <Text
          style={
            pdfStyles.infoLabel
          }
        >
          {label}
        </Text>

        <Text
          style={
            pdfStyles.infoValue
          }
        >
          {safeText(
            value
          )}
        </Text>
      </View>
    </View>
  );
}

